// Builds tokens/*.json (DTCG) into CSS, TS and GLSL. Run: pnpm tokens:build
import StyleDictionary from 'style-dictionary';

const hexToVec3 = (hex) => {
  let h = String(hex).replace('#', '');
  if (h.length === 3) h = h.split('').map((c) => c + c).join('');
  const n = [0, 2, 4].map((i) => parseInt(h.slice(i, i + 2), 16) / 255);
  return `vec3(${n.map((v) => v.toFixed(4)).join(', ')})`;
};
const toFloat = (v) => {
  const n = Number(v);
  return Number.isInteger(n) ? `${n}.0` : String(n);
};
const durationToSeconds = (v) => {
  const s = String(v);
  if (s.endsWith('ms')) return toFloat(parseFloat(s) / 1000);
  if (s.endsWith('s')) return toFloat(parseFloat(s));
  return toFloat(s);
};

StyleDictionary.registerFormat({
  name: 'glsl/constants',
  format: ({ dictionary }) => {
    const header = '// GENERATED by tokens/build.mjs — do not edit. Source: tokens/*.json\n#ifndef TOKENS_GLSL\n#define TOKENS_GLSL\n\n';
    const lines = dictionary.allTokens.flatMap((t) => {
      const value = t.$value ?? t.value;
      const type = t.$type ?? t.type;
      const name = t.path.join('_').replace(/[^a-zA-Z0-9_]/g, '_').toUpperCase();
      if (type === 'color') return [`const vec3 COLOR_${name.replace(/^COLOR_/, '')} = ${hexToVec3(value)};`];
      if (type === 'duration') return [`const float ${name} = ${durationToSeconds(value)}; // seconds`];
      if (type === 'number') return [`const float ${name} = ${toFloat(value)};`];
      if (type === 'cubicBezier' && Array.isArray(value)) return [`const vec4 ${name} = vec4(${value.map(toFloat).join(', ')});`];
      return [];
    });
    return header + lines.join('\n') + '\n\n#endif\n';
  },
});

const sd = new StyleDictionary({
  source: ['tokens/**/*.json'],
  usesDtcg: true,
  log: { verbosity: 'default', warnings: 'error' },
  platforms: {
    css: {
      transformGroup: 'css',
      buildPath: 'src/styles/generated/',
      files: [{ destination: 'tokens.css', format: 'css/variables', options: { outputReferences: true } }],
    },
    ts: {
      transformGroup: 'js',
      buildPath: 'src/tokens/generated/',
      files: [
        { destination: 'tokens.js', format: 'javascript/es6' },
        { destination: 'tokens.d.ts', format: 'typescript/es6-declarations' },
      ],
    },
    glsl: {
      transforms: ['name/constant'],
      buildPath: 'src/gl/glsl/generated/',
      files: [{ destination: 'tokens.glsl', format: 'glsl/constants' }],
    },
  },
});

await sd.buildAllPlatforms();
